  int sum = numbers.fold(0, (prev, element) => prev + element);
  print('Sum of numbers: $sum');
  List<String> fruits = ['apple', 'banana', 'cherry'];
  String fruitList = fruits.join(', ');
  print('Fruits: $fruitList');
  Map<String, int> fruitCount = {'apple': 2, 'banana': 3};
  fruitCount.forEach((key, value) => print('$key: $value'));
}
